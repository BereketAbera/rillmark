test('all three examples fit a phone and the app navigation works', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/#/examples/dashboard')
  await expect(page.getByRole('heading', { name: 'Good work, in progress.' })).toBeVisible()
  for (const screen of ['dashboard', 'settings', 'discovery']) {
    if (screen !== 'dashboard') await page.getByRole('navigation', { name: 'Fieldwork example navigation' }).getByRole('link', { name: screen === 'settings' ? 'Settings' : 'Discover', exact: true }).click()
    await expect(page.getByRole('heading', { name: screen === 'dashboard' ? 'Good work, in progress.' : screen === 'settings' ? 'Make yourself at home.' : 'A little curiosity. A new point of view.' })).toBeVisible()
    await expect(page.locator('.fw-app')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    if (screen === 'settings') {
      expect(await page.locator('.fw-settings-card').evaluate((element) => element.getBoundingClientRect().right < window.innerWidth - 12)).toBe(true)
      expect(await page.getByRole('tab', { name: 'Preferences', exact: true }).evaluate((element) => element.getBoundingClientRect().right < window.innerWidth - 12)).toBe(true)
    }
    await page.screenshot({ path: testInfo.outputPath(`${screen}-mobile.png`), fullPage: true, animations: 'disabled' })
  }
  await page.getByRole('navigation', { name: 'Fieldwork example navigation' }).getByRole('link', { name: 'Workspace', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Good work, in progress.' })).toBeVisible()
})

test('capture the three complete screens in both themes without browser errors', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1080 })
  for (const theme of ['light', 'dark']) {
    for (const screen of ['dashboard', 'settings', 'discovery']) {
      await page.goto(`/#/examples/${screen}`)
      await expect(page.locator('.fw-app')).toBeVisible()
      if (theme === 'dark' && !await page.locator('html').evaluate((element) => element.classList.contains('dark'))) await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click()
      if (theme === 'light' && await page.locator('html').evaluate((element) => element.classList.contains('dark'))) await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
      await page.screenshot({ path: testInfo.outputPath(`${screen}-${theme}.png`), fullPage: true, animations: 'disabled' })
    }
  }
  expect(errors).toEqual([])
})
