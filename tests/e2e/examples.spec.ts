test('preferences work with keyboard, persist, and require confirmation to reset local demo data', async ({ page }) => {
  await page.goto('/#/examples/settings')
  await page.getByRole('tab', { name: 'Preferences', exact: true }).click()
  const weekly = page.getByRole('radio', { name: /A weekly digest/ })
  await weekly.focus()
  // Radix moves roving focus on the next task; hold the key through that move.
  await page.keyboard.down('ArrowDown')
  await expect(page.getByRole('radio', { name: /As things happen/ })).toBeChecked()
  await page.keyboard.up('ArrowDown')
  await page.getByRole('switch', { name: 'When someone mentions me' }).uncheck()
  await page.getByRole('switch', { name: 'Notes from the studio' }).check()
  const slider = page.getByRole('slider', { name: 'Weekly focus goal in hours' })
  await slider.focus()
  await slider.press('ArrowRight')
  await expect(slider).toHaveAttribute('aria-valuenow', '22')
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click()
  await page.reload()
  await page.getByRole('tab', { name: 'Preferences', exact: true }).click()
  await expect(page.getByRole('radio', { name: /As things happen/ })).toBeChecked()
  await expect(page.getByRole('switch', { name: 'When someone mentions me' })).not.toBeChecked()
  await expect(page.getByRole('switch', { name: 'Notes from the studio' })).toBeChecked()
  await expect(page.getByRole('slider', { name: 'Weekly focus goal in hours' })).toHaveAttribute('aria-valuenow', '22')
  const reset = page.getByRole('button', { name: 'Reset demo', exact: true })
  await reset.click()
  const confirmation = page.getByRole('alertdialog', { name: 'Reset this local demo?' })
  await expect(confirmation).toBeVisible()
  await page.getByRole('button', { name: 'Keep my changes', exact: true }).click()
  await expect(reset).toBeFocused()
  await expect(slider).toHaveAttribute('aria-valuenow', '22')
  await reset.click()
  await confirmation.getByRole('button', { name: 'Reset demo data', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await expect(slider).toHaveAttribute('aria-valuenow', '20')
  await expect(page.getByRole('radio', { name: /A weekly digest/ })).toBeChecked()
  await expect(page.getByRole('switch', { name: 'When someone mentions me' })).toBeChecked()
})

