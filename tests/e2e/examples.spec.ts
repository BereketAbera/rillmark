  await page.getByRole('combobox', { name: 'Filter projects by status' }).click()
  await page.getByRole('option', { name: 'In review', exact: true }).click()
  await expect(page.locator('.fw-table tbody tr')).toHaveCount(4)
  await expect(page.getByRole('button', { name: 'Stillwater packaging', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Filter projects by status' }).click()
  await page.getByRole('option', { name: 'All statuses', exact: true }).click()
  await page.getByRole('button', { name: 'Project', exact: true }).click()
