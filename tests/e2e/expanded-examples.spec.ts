import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'

async function fillIntention(page: Page) {
  await page.getByRole('textbox', { name: 'Project name', exact: true }).fill('Common Ground, a new chapter')
  await page.getByRole('textbox', { name: 'Who is it for?', exact: true }).fill('Common Ground community gardens')
  await page.getByRole('textbox', { name: 'What should be different when we’re done?', exact: true }).fill('Help neighbors find a growing space, meet the people behind it, and feel confident joining in.')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Give the work a little shape.' })).toBeVisible()
}

test('brief validates each step, saves a draft, keeps file names private, finishes and resets', async ({ page }) => {
  await page.goto('/#/examples/onboarding')
  await expect(page.getByRole('heading', { name: 'A good beginning changes everything.' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Project brief steps' }).getByRole('button', { name: /The starting point/ })).toBeDisabled()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByText('Give your project a name with at least 3 characters.')).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Project name', exact: true })).toBeFocused()
  await fillIntention(page)
  const people = page.getByRole('spinbutton', { name: 'People on the team' })
  await people.fill('')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByText('Choose a whole number from 1 to 20 people.')).toBeVisible()
  await expect(people).toBeFocused()
  await people.fill('4')
  await page.getByRole('button', { name: 'More people', exact: true }).click()
  await expect(people).toHaveValue('5')
  await page.getByRole('spinbutton', { name: 'Duration in weeks' }).fill('8')
  await page.getByRole('spinbutton', { name: 'Working budget (USD)' }).fill('18500')
  await page.getByRole('button', { name: 'Remove Brand strategy', exact: true }).click()
  await page.getByRole('button', { name: 'Remove Visual identity', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByText('Add at least one deliverable.')).toBeVisible()
  const deliverables = page.getByRole('textbox', { name: 'Deliverables' })
  await expect(deliverables).toBeFocused()
  await deliverables.fill('Community website')
  await deliverables.press('Enter')
  await expect(page.getByRole('button', { name: 'Remove Community website', exact: true })).toBeVisible()
  const fileInput = page.getByLabel('Reference files', { exact: true })
  await fileInput.setInputFiles({ name: 'notes.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('not allowed') })
  await expect(page.getByText('notes.exe: file type is not accepted.')).toBeVisible()
  await fileInput.setInputFiles({ name: 'garden-notes.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nLocal example reference') })
  await expect(page.getByRole('button', { name: 'Remove garden-notes.pdf', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('spinbutton', { name: 'People on the team' })).toHaveValue('5')
  await expect(page.getByText('Saved reference names', { exact: true })).toBeVisible()
  await expect(page.getByText('garden-notes.pdf', { exact: true })).toBeVisible()
  expect(await page.getByLabel('Reference files', { exact: true }).evaluate((element) => (element as HTMLInputElement).files?.length)).toBe(0)
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'One last look. Then, begin.' })).toBeFocused()
  await expect(page.locator('.fw-brief-review')).toContainText('$18,500')
  await page.getByRole('button', { name: 'Finish brief', exact: true }).click()
  await expect(page.getByText('Confirm that you have reviewed the brief before finishing.')).toBeVisible()
  const reviewed = page.getByRole('checkbox', { name: /I’ve reviewed this brief/ })
  await expect(reviewed).toBeFocused()
  await reviewed.check()
  await page.getByRole('button', { name: 'Finish brief', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'The first page is written.' })).toBeFocused()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download brief', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('fieldwork-project-brief.txt')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'The first page is written.' })).toBeVisible()
  const reset = page.getByRole('button', { name: 'Reset brief', exact: true })
  await reset.click()
  await page.getByRole('button', { name: 'Keep this brief', exact: true }).click()
  await expect(reset).toBeFocused()
  await reset.click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Reset brief data', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Project name', exact: true })).toHaveValue('')
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Project name', exact: true })).toHaveValue('')
})

test('inbox filters, persists read and saved state, saves private notes and restores focus', async ({ page }) => {
  await page.goto('/#/examples/activity')
  await expect(page.getByRole('heading', { name: 'Keep the work in view.' })).toBeVisible()
  const search = page.getByRole('searchbox', { name: 'Search studio activity' })
  await search.fill('Maya')
  await expect(page.locator('.fw-update')).toHaveCount(2)
  await page.getByRole('combobox', { name: 'Filter activity by type' }).click()
  await page.getByRole('option', { name: 'Milestone', exact: true }).click()
  await expect(page.locator('.fw-update')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Ready for the next pair of hands.', exact: true })).toBeVisible()
  await search.fill('No such studio update')
  await expect(page.getByRole('heading', { name: 'Nothing in this corner, yet.' })).toBeVisible()
  await page.getByRole('button', { name: 'See all activity', exact: true }).click()
  const title = 'A little more room for the story.'
  await page.getByRole('button', { name: `Save: ${title}`, exact: true }).click()
  await page.getByRole('button', { name: `Mark read: ${title}`, exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Saved 1', exact: true }).click()
  await expect(page.locator('.fw-update')).toHaveCount(1)
  await expect(page.getByRole('button', { name: `Mark unread: ${title}`, exact: true })).toBeVisible()
  const open = page.getByRole('button', { name: title, exact: true })
  await open.click()
  const detail = page.getByRole('dialog', { name: title, exact: true })
  await expect(detail.getByRole('heading', { name: 'A useful next step' })).toBeVisible()
  await detail.getByRole('textbox', { name: 'A note to yourself' }).fill('Try the membership card at 85 mm before Thursday.')
  await detail.getByRole('button', { name: 'Save personal note', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(open).toBeFocused()
  await page.reload()
  await page.getByRole('button', { name: title, exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'A note to yourself' })).toHaveValue('Try the membership card at 85 mm before Thursday.')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Saved 1', exact: true }).click()
  await page.getByRole('button', { name: `Unsave: ${title}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Keep the useful things close.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Saved 0', exact: true })).toBeFocused()
})

test('inbox context menu and keyboard command actions work without a pointer', async ({ page }) => {
  await page.goto('/#/examples/activity')
  const update = page.getByRole('article', { name: 'Harbor identity: A little more room for the story.' })
  await update.focus()
  await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('menu')).toBeVisible()
  await page.getByRole('menuitem', { name: 'Save for later', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Unsave: A little more room for the story.', exact: true })).toBeVisible()
  await update.focus()
  await page.keyboard.press('Shift+F10')
  await page.getByRole('menuitem', { name: 'Read the full update', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'A little more room for the story.', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(update).toBeFocused()
  await page.keyboard.press('Control+k')
  const command = page.getByRole('dialog', { name: 'Find your next move', exact: true })
  const commandSearch = command.getByRole('searchbox', { name: 'Search updates and actions' })
  await expect(commandSearch).toBeFocused()
  await commandSearch.fill('mark all')
  await commandSearch.press('ArrowDown')
  await expect(command.getByRole('button', { name: /Mark all updates as read/ })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(command).toBeHidden()
  await expect(page.getByRole('button', { name: /Quick actions/ })).toBeFocused()
  await page.getByRole('button', { name: 'Unread 0', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A little breathing room.' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Unread 0', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Quick actions/ }).click()
  await page.getByRole('searchbox', { name: 'Search updates and actions' }).fill('Start a project brief')
  await page.getByRole('searchbox', { name: 'Search updates and actions' }).press('Enter')
  await expect(page.getByRole('heading', { name: 'A good beginning changes everything.' })).toBeVisible()
})

for (const preset of ['fieldnotes', 'studio', 'play']) {
  test(`expanded examples render accessibly in ${preset}, light and dark`, async ({ page }, testInfo) => {
    test.setTimeout(90_000)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    for (const mode of ['light', 'dark']) {
      for (const screen of ['onboarding', 'activity']) {
        await page.goto(`/#/examples/${screen}`)
        await expect(page.getByRole('heading', { name: screen === 'onboarding' ? 'A good beginning changes everything.' : 'Keep the work in view.' })).toBeVisible()
        await page.getByRole('combobox', { name: 'Visual preset', exact: true }).selectOption(preset)
        if (await page.locator('html').evaluate((element) => element.classList.contains('dark')) !== (mode === 'dark')) await page.getByRole('button', { name: `Switch to ${mode} theme`, exact: true }).click()
        await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
        expect((await new AxeBuilder({ page }).include('.fw-app').analyze()).violations).toEqual([])
        await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); window.scrollTo({ top: 0, behavior: 'instant' }) })
        await page.screenshot({ path: testInfo.outputPath(`${screen}-${preset}-${mode}.png`), fullPage: true, animations: 'disabled' })
      }
    }
    expect(errors).toEqual([])
  })
}

